export const scores = (a: Answers): Record<AxisKey, number> => {
  const raw = {} as Record<AxisKey, number>;
  const cnt = {} as Record<AxisKey, number>;
  for (const k of AXIS_ORDER) { raw[k] = 0; cnt[k] = 0; }
  for (const q of QUESTIONS) {
    if (!q.axis) continue;
    raw[q.axis] += a[q.id] ?? 0;
    cnt[q.axis] += 1;
  }
  const out = {} as Record<AxisKey, number>;
  for (const k of AXIS_ORDER) out[k] = Math.round((raw[k] / (cnt[k] * 3)) * 100);
  return out;
};

export const isNotDev = (a: Answers): boolean => a.role === ROLE_NOT_DEV;

/** Не разработчик или стаж меньше двух лет: дальше вопросы не задаём. */
export const isExit = (a: Answers): boolean => isNotDev(a) || a.exp === EXP_UNDER_TWO;

export const outcome = (a: Answers): Outcome => {
  if (isExit(a)) return 'A';
  const s = scores(a);
  const v = AXIS_ORDER.map((k) => s[k]);
  const avg = v.reduce((x, y) => x + y, 0) / v.length;
  if (avg >= 80 && Math.min(...v) >= 60) return 'B';
  if (s.agents < 45) return 'C';
  if (s.spec >= 55 && s.ctx >= 55 && s.legacy < 55) return 'E';
  return 'D';
};

/** Два главных вектора роста. У «Ассистента» только основы, у «Личного чемпиона» первым всегда legacy. */
export const weakest = (s: Record<AxisKey, number>, oc: Outcome): AxisKey[] => {
  const pool: AxisKey[] = oc === 'C' ? ['spec', 'ctx', 'agents'] : AXIS_ORDER;
  let order = pool.slice().sort((x, y) => s[x] - s[y]);
  if (oc === 'E') order = ['legacy', ...order.filter((k) => k !== 'legacy')];
  if (oc === 'C') order = ['agents', ...order.filter((k) => k !== 'agents')];
  return order.slice(0, 2);
};

/**
 * Комментарий карточки контакта в AXL: профиль, оси, векторы и ответы словами,
 * чтобы менеджер читал без ключа. Функция axl-lead режет комментарий по 1500
 * знакам молча, поэтому худший случай по длине держит _check-diagnostic.mjs.
 */
export const buildComment = (
  a: Answers,
  extra: { goal?: string; telegram?: string },
  date: string,
): string => {
  const s = scores(a);
  const oc = outcome(a);
  const lines = [
    `Диагностика AI-разработки, ${date}`,
    `Профиль: ${PROFILES[oc]?.name ?? oc} (${oc})`,
    `Оси: ${AXIS_ORDER.map((k) => `${AXES[k]} ${s[k]}%`).join(', ')}`,
    `Векторы роста: ${weakest(s, oc).map((k) => GAPS[k].title).join('; ')}`,
    extra.goal ? `Цель: ${extra.goal}` : '',
    extra.telegram ? `Telegram: ${extra.telegram}` : '',
    ...QUESTIONS.map((q) => (a[q.id] === undefined ? '' : `${q.label}: ${q.opts[a[q.id]]}`)),
  ];
  return lines.filter(Boolean).join('\n');
};
