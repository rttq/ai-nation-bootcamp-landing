// Диагностика AI-разработки на /dev/diagnostika/: вопросы, тексты результата,
// подсчёт и строка для комментария контакта в CRM AXL. Страница
// (Diagnostic.astro) только рисует то, что считается здесь.
//
// Файл самодостаточный, без импортов: его же гоняет `_check-diagnostic.mjs`
// (node --experimental-strip-types), поэтому только стираемый TypeScript — без
// enum и namespace.
//
// Подсчёт: у вопроса с осью номер выбранного варианта (0–3) и есть балл. Ось
// считается долей от максимума, в процентах. Первые два вопроса (роль, стаж)
// баллов не дают, они отсекают тех, кому буткемп пока не подходит.

export type AxisKey = 'spec' | 'ctx' | 'agents' | 'rag' | 'legacy';
export type Outcome = 'A' | 'B' | 'C' | 'D' | 'E';
/** Номер выбранного варианта по id вопроса. */
export type Answers = Record<string, number>;

export interface Question {
  id: string;
  /** Короткое имя вопроса: под ним ответ попадает в комментарий контакта. */
  label: string;
  axis?: AxisKey;
  title: string;
  hint?: string;
  /** «Терминал» под вопросом. Разметка своя (`<span class="dg-dim">`), текст наш. */
  term?: string;
  opts: string[];
}

